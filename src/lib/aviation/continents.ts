/** Subdivide arestas longas (passo em graus) para a projeção curvar o contorno. */
export function densify(ring: Ring, maxStepDeg: number = 2): Ring {
  const out: (readonly [number, number])[] = [];
  ring.forEach((point, index) => {
    const next = ring[index + 1];
    out.push(point);
    if (next === undefined) {
      return;
    }
    const steps = Math.ceil(Math.max(Math.abs(next[0] - point[0]), Math.abs(next[1] - point[1])) / maxStepDeg);
    for (let step = 1; step < steps; step += 1) {
      const t = step / steps;
      out.push([point[0] + (next[0] - point[0]) * t, point[1] + (next[1] - point[1]) * t]);
    }
  });
  return out;
}
